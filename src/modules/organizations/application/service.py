"""Company settings, departments and staff accounts (P0, spec §3).

Hierarchy (``CREATABLE_ROLES``): the director creates heads of sales and other
staff of the company. Hiring and dismissal are the director's decision: a head
of sales manages their department's staff (role, password reset) and may only
*request* a hire (roles they are allowed to give, their own department) or a
dismissal (a member of their department); the account is created or deactivated
when the director approves the request.
Passwords are never readable: a temporary password is generated by the server,
returned once and must be changed at first sign-in. Accounts are deactivated,
never deleted.
"""

from __future__ import annotations

import re
from collections.abc import Callable
from dataclasses import replace
from uuid import UUID
from zoneinfo import available_timezones

from modules.access_control.domain.rbac import (
    CREATABLE_ROLES,
    AccessPolicy,
    Permission,
    Principal,
    Role,
    Scope,
)
from modules.audit.application.ports import AuditLog
from modules.audit.domain.entry import AuditEntry
from modules.organizations.application.ports import (
    Company,
    DepartmentInfo,
    NewAccount,
    NewStaffRequest,
    OrganizationStore,
    PasswordGenerator,
    StaffMember,
    StaffRequestInfo,
    WorkHandover,
)
from shared.application.ports import UnitOfWork
from shared.domain.errors import (
    AccessDeniedError,
    ConflictError,
    DomainValidationError,
    NotFoundError,
)

_COUNTRY = re.compile(r"^[A-Z]{2}$")
_CURRENCY = re.compile(r"^[A-Z]{3}$")
_LOGIN = re.compile(r"^[A-Za-z0-9._@+-]{3,150}$")
MAX_NAME = 150
_REQUEST_STATUSES = ("pending", "approved", "rejected", "cancelled")


class OrganizationService:
    def __init__(
        self,
        store: OrganizationStore,
        audit: AuditLog,
        uow: UnitOfWork,
        passwords: PasswordGenerator,
        *,
        handover: WorkHandover | None = None,
        policy: AccessPolicy | None = None,
    ) -> None:
        self._handover = handover
        self._store = store
        self._audit = audit
        self._uow = uow
        self._passwords = passwords
        self._policy = policy or AccessPolicy()

    # --- company ----------------------------------------------------------------

    def company(self, principal: Principal) -> Company:
        return self._store.company(principal.tenant_id)

    def update_company(
        self,
        principal: Principal,
        *,
        name: str | None = None,
        country: str | None = None,
        currency: str | None = None,
        timezone: str | None = None,
    ) -> Company:
        self._policy.require(principal, Permission.COMPANY_SETTINGS_MANAGE)
        current = self._store.company(principal.tenant_id)
        changes: dict[str, str] = {}
        if name is not None:
            changes["name"] = _clean(name, "name", 200)
        if country is not None:
            if not _COUNTRY.match(country):
                raise DomainValidationError("country must be an ISO 3166-1 alpha-2 code, e.g. KG.")
            changes["country"] = country
        if currency is not None:
            if not _CURRENCY.match(currency):
                raise DomainValidationError("currency must be an ISO 4217 code, e.g. KGS.")
            changes["currency"] = currency
        if timezone is not None:
            if timezone not in available_timezones():
                raise DomainValidationError("timezone must be an IANA name, e.g. Asia/Bishkek.")
            changes["timezone"] = timezone
        updated = replace(
            current,
            name=changes.get("name", current.name),
            country=changes.get("country", current.country),
            currency=changes.get("currency", current.currency),
            timezone=changes.get("timezone", current.timezone),
        )
        with self._uow:
            self._store.save_company(updated)
            self._record(principal, "company.updated", "company", str(current.id), tuple(changes))
        return updated

    # --- departments ------------------------------------------------------------

    def departments(self, principal: Principal) -> list[DepartmentInfo]:
        self._policy.require(principal, Permission.STAFF_VIEW)
        return self._store.departments(principal.tenant_id)

    def create_department(self, principal: Principal, name: str) -> DepartmentInfo:
        self._policy.require(principal, Permission.DEPARTMENTS_MANAGE)
        clean = _clean(name, "name", 100)
        with self._uow:
            if self._store.department_name_taken(principal.tenant_id, clean):
                raise ConflictError("A department with this name already exists.")
            department = self._store.add_department(principal.tenant_id, clean)
            self._record(principal, "department.created", "department", str(department.id), ())
        return department

    def update_department(
        self,
        principal: Principal,
        department_id: UUID,
        *,
        name: str | None = None,
        is_active: bool | None = None,
    ) -> DepartmentInfo:
        self._policy.require(principal, Permission.DEPARTMENTS_MANAGE)
        with self._uow:
            current = self._store.department(principal.tenant_id, department_id)
            if current is None:
                raise NotFoundError("Department not found.")
            updated = current
            if name is not None:
                clean = _clean(name, "name", 100)
                if self._store.department_name_taken(
                    principal.tenant_id, clean, exclude=current.id
                ):
                    raise ConflictError("A department with this name already exists.")
                updated = replace(updated, name=clean)
            if is_active is not None:
                updated = replace(updated, is_active=is_active)
            self._store.save_department(principal.tenant_id, updated)
            self._record(principal, "department.updated", "department", str(current.id), ())
        return updated

    # --- staff --------------------------------------------------------------------

    def staff(self, principal: Principal) -> list[StaffMember]:
        scope = self._policy.require(principal, Permission.STAFF_VIEW)
        if scope is Scope.ALL:
            return self._store.staff(principal.tenant_id)
        if principal.department_id is None:
            return []  # a head of sales without a department sees nobody but themself
        return self._store.staff(principal.tenant_id, principal.department_id)

    def member_names(self, principal: Principal) -> list[tuple[UUID, str]]:
        """(user id, full name) of the company's active staff — for every member.

        Names only: contacts, roles, departments and activity stay behind staff.view.
        """
        return [
            (m.user_id, m.full_name) for m in self._store.staff(principal.tenant_id) if m.is_active
        ]

    def create_options(self, principal: Principal) -> dict[str, object]:
        """What the caller may create: the director directly, a head of sales by request."""
        scope = self._policy.require(principal, Permission.STAFF_MANAGE)
        roles = [r.value for r in CREATABLE_ROLES.get(principal.role, ())]
        fixed = principal.department_id if scope is not Scope.ALL else None
        departments = [d for d in self._store.departments(principal.tenant_id) if d.is_active]
        if scope is not Scope.ALL:
            departments = [d for d in departments if d.id == fixed]
        return {
            "creatable_roles": roles if scope is Scope.ALL or fixed is not None else [],
            "departments": departments,
            "fixed_department_id": fixed,
            "mode": "direct" if scope is Scope.ALL else "request",
        }

    def create_member(
        self,
        principal: Principal,
        *,
        first_name: str,
        last_name: str,
        role: str,
        login: str | None = None,
        email: str | None = None,
        phone: str = "",
        department_id: UUID | None = None,
    ) -> tuple[StaffMember, str]:
        """Create an account; returns the member and its temporary password (shown once)."""
        scope = self._require_director(principal)
        new_role = self._allowed_role(principal, role)
        department = self._target_department(principal, scope, department_id)
        with self._uow:
            return self._create_account(
                principal,
                first_name=first_name,
                last_name=last_name,
                role=new_role,
                login=login,
                email=email,
                phone=phone,
                department_id=department,
            )

    def _create_account(
        self,
        principal: Principal,
        *,
        first_name: str,
        last_name: str,
        role: Role,
        login: str | None,
        email: str | None,
        phone: str,
        department_id: UUID | None,
    ) -> tuple[StaffMember, str]:
        first, last = _clean(first_name, "first_name", MAX_NAME), last_name.strip()[:MAX_NAME]
        chosen = (login or "").strip() or _login_from(first, last)
        if not _LOGIN.match(chosen):
            raise DomainValidationError("login may contain letters, digits and . _ @ + - (3-150).")
        clean_email = (email or "").strip().lower() or None
        password = self._passwords()
        if self._store.login_taken(chosen):
            if login:
                raise ConflictError("This login is already taken.")
            chosen = _unique_login(chosen, self._store.login_taken)
        if clean_email and self._store.email_taken(clean_email):
            raise ConflictError("This e-mail is already used by another account.")
        member = self._store.create_account(
            principal.tenant_id,
            NewAccount(
                login=chosen,
                first_name=first,
                last_name=last,
                email=clean_email,
                phone=phone.strip()[:16],
                role=role.value,
                department_id=department_id,
                created_by=principal.user_id,
            ),
            password,
        )
        self._record(principal, "staff.created", "membership", str(member.membership_id), ("role",))
        return member, password

    # --- hire and dismissal requests (head of sales -> director) -------------------

    def request_hire(
        self,
        principal: Principal,
        *,
        first_name: str,
        last_name: str,
        role: str,
        login: str | None = None,
        email: str | None = None,
        phone: str = "",
    ) -> StaffRequestInfo:
        """A head of sales asks to hire into their own department; nothing is created yet."""
        department = self._requesting_department(principal)
        new_role = self._allowed_role(principal, role)
        first, last = _clean(first_name, "first_name", MAX_NAME), last_name.strip()[:MAX_NAME]
        chosen = (login or "").strip()
        if chosen and not _LOGIN.match(chosen):
            raise DomainValidationError("login may contain letters, digits and . _ @ + - (3-150).")
        clean_email = (email or "").strip().lower() or None
        with self._uow:
            if chosen and self._store.login_taken(chosen):
                raise ConflictError("This login is already taken.")
            if clean_email and self._store.email_taken(clean_email):
                raise ConflictError("This e-mail is already used by another account.")
            request = self._store.add_request(
                principal.tenant_id,
                NewStaffRequest(
                    kind="hire",
                    department_id=department,
                    requested_by=principal.user_id,
                    first_name=first,
                    last_name=last,
                    login=chosen,
                    email=clean_email,
                    phone=phone.strip()[:16],
                    role=new_role.value,
                ),
            )
            self._record(principal, "staff.hire_requested", "staff_request", str(request.id), ())
        return request

    def request_dismissal(
        self, principal: Principal, membership_id: UUID, reason: str = ""
    ) -> StaffRequestInfo:
        """A head of sales asks to dismiss a member of their department."""
        department = self._requesting_department(principal)
        scope = self._policy.require(principal, Permission.STAFF_MANAGE)
        with self._uow:
            member = self._managed(principal, scope, membership_id)
            if not member.is_active:
                raise ConflictError("This account is already deactivated.")
            if self._store.pending_dismissal_exists(member.membership_id):
                raise ConflictError("A dismissal request for this person is already pending.")
            request = self._store.add_request(
                principal.tenant_id,
                NewStaffRequest(
                    kind="dismiss",
                    department_id=department,
                    requested_by=principal.user_id,
                    target_membership_id=member.membership_id,
                    reason=reason.strip()[:500],
                ),
            )
            self._record(
                principal, "staff.dismissal_requested", "staff_request", str(request.id), ()
            )
        return request

    def staff_requests(
        self, principal: Principal, status: str | None = None
    ) -> list[StaffRequestInfo]:
        """The director sees the company's requests; a head of sales — their department's."""
        scope = self._policy.require(principal, Permission.STAFF_MANAGE)
        if status is not None and status not in _REQUEST_STATUSES:
            raise DomainValidationError("Unknown request status.")
        if scope is Scope.ALL:
            return self._store.staff_requests(principal.tenant_id, None, status)
        if principal.department_id is None:
            return []
        return self._store.staff_requests(principal.tenant_id, principal.department_id, status)

    def approve_request(
        self, principal: Principal, request_id: UUID
    ) -> tuple[StaffRequestInfo, str | None]:
        """The director approves: hire creates the account (temporary password returned once),
        dismissal deactivates it."""
        self._require_director(principal)
        with self._uow:
            request = self._pending(principal, request_id)
            password: str | None = None
            result: UUID | None = None
            if request.kind == "hire":
                department = self._store.department(principal.tenant_id, request.department.id)
                if department is None or not department.is_active:
                    raise ConflictError("The department of this request is no longer active.")
                member, password = self._create_account(
                    principal,
                    first_name=request.first_name,
                    last_name=request.last_name,
                    role=self._allowed_role(principal, request.role),
                    login=request.login or None,
                    email=request.email,
                    phone=request.phone,
                    department_id=department.id,
                )
                result = member.membership_id
            else:
                target = (
                    self._store.member(principal.tenant_id, request.target_membership_id)
                    if request.target_membership_id is not None
                    else None
                )
                if target is not None and target.is_active:
                    if target.user_id == principal.user_id:
                        raise DomainValidationError("You cannot deactivate your own account.")
                    # The head of sales who asked takes over the open tasks of their department.
                    self._offboard(principal, target, recipient=request.requested_by)
            decided = self._store.decide_request(
                principal.tenant_id,
                request.id,
                status="approved",
                decided_by=principal.user_id,
                result_membership_id=result,
            )
            self._record(principal, "staff.request_approved", "staff_request", str(request.id), ())
        return decided, password

    def reject_request(
        self, principal: Principal, request_id: UUID, note: str = ""
    ) -> StaffRequestInfo:
        self._require_director(principal)
        with self._uow:
            request = self._pending(principal, request_id)
            decided = self._store.decide_request(
                principal.tenant_id,
                request.id,
                status="rejected",
                decided_by=principal.user_id,
                note=note.strip()[:500],
            )
            self._record(principal, "staff.request_rejected", "staff_request", str(request.id), ())
        return decided

    def cancel_request(self, principal: Principal, request_id: UUID) -> StaffRequestInfo:
        """The author withdraws their own pending request."""
        self._policy.require(principal, Permission.STAFF_MANAGE)
        with self._uow:
            request = self._pending(principal, request_id)
            if request.requested_by != principal.user_id:
                raise AccessDeniedError("Only the author can withdraw a request.")
            decided = self._store.decide_request(
                principal.tenant_id, request.id, status="cancelled", decided_by=principal.user_id
            )
            self._record(principal, "staff.request_cancelled", "staff_request", str(request.id), ())
        return decided

    def _offboard(
        self, principal: Principal, member: StaffMember, *, recipient: UUID
    ) -> StaffMember:
        """Deactivate an account (sign-in blocked) and hand over its open tasks.

        Rule: open tasks go to ``recipient`` — the head of sales who requested the dismissal,
        or the director who deactivated directly. Deals, customers, done tasks, meetings and
        the audit trail stay with the person as history; the director can hand deals and
        customers over explicitly. Nothing is deleted.
        """
        updated = self._store.deactivate(principal.tenant_id, member.membership_id)
        self._record(principal, "staff.deactivated", "membership", str(member.membership_id), ())
        if self._handover is not None:
            self._handover.hand_over(member.user_id, recipient, principal.user_id)
        return updated

    def _requesting_department(self, principal: Principal) -> UUID:
        scope = self._policy.require(principal, Permission.STAFF_MANAGE)
        if scope is Scope.ALL:
            raise DomainValidationError(
                "The director hires and dismisses directly; requests are for heads of sales."
            )
        if principal.department_id is None:
            raise DomainValidationError("You are not assigned to a department.")
        return principal.department_id

    def _pending(self, principal: Principal, request_id: UUID) -> StaffRequestInfo:
        scope = self._policy.require(principal, Permission.STAFF_MANAGE)
        request = self._store.staff_request(principal.tenant_id, request_id)
        # Another department's request is not found for a head of sales.
        if request is None or (
            scope is not Scope.ALL and request.department.id != principal.department_id
        ):
            raise NotFoundError("Request not found.")
        if request.status != "pending":
            raise ConflictError("The request has already been decided.")
        return request

    def update_member(
        self,
        principal: Principal,
        membership_id: UUID,
        *,
        role: str | None = None,
        department_id: UUID | None = None,
        clear_department: bool = False,
    ) -> StaffMember:
        scope = self._policy.require(principal, Permission.STAFF_MANAGE)
        with self._uow:
            member = self._managed(principal, scope, membership_id)
            new_role = self._allowed_role(principal, role).value if role is not None else None
            if department_id is not None or clear_department:
                if scope is not Scope.ALL:
                    raise AccessDeniedError("Only the director can move staff between departments.")
                if department_id is not None:
                    self._existing_department(principal, department_id)
            updated = self._store.update_member(
                principal.tenant_id,
                member.membership_id,
                role=new_role,
                department_id=department_id,
                clear_department=clear_department,
            )
            changed = tuple(
                f for f, v in (("role", role), ("department", department_id)) if v is not None
            ) or (("department",) if clear_department else ())
            self._record(principal, "staff.updated", "membership", str(membership_id), changed)
        return updated

    def deactivate(self, principal: Principal, membership_id: UUID) -> StaffMember:
        scope = self._require_director(principal)
        with self._uow:
            member = self._managed(principal, scope, membership_id)
            if member.user_id == principal.user_id:
                raise DomainValidationError("You cannot deactivate your own account.")
            if not member.is_active:
                return member
            return self._offboard(principal, member, recipient=principal.user_id)

    def reset_password(self, principal: Principal, membership_id: UUID) -> str:
        scope = self._policy.require(principal, Permission.STAFF_MANAGE)
        password = self._passwords()
        with self._uow:
            member = self._managed(principal, scope, membership_id)
            if not member.is_active:
                raise ConflictError("Reactivate the account before resetting its password.")
            self._store.set_temporary_password(principal.tenant_id, member.membership_id, password)
            self._record(principal, "staff.password_reset", "membership", str(membership_id), ())
        return password

    # --- helpers ------------------------------------------------------------------

    def _require_director(self, principal: Principal) -> Scope:
        """Hiring and dismissal need company-wide staff rights (the director)."""
        scope = self._policy.require(principal, Permission.STAFF_MANAGE)
        if scope is not Scope.ALL:
            raise AccessDeniedError("Hiring and dismissal are confirmed by the director.")
        return scope

    def _allowed_role(self, principal: Principal, role: str) -> Role:
        try:
            wanted = Role(role)
        except ValueError as exc:
            raise DomainValidationError("Unknown role.") from exc
        if wanted not in CREATABLE_ROLES.get(principal.role, ()):
            raise AccessDeniedError("You cannot give this role.")
        return wanted

    def _target_department(
        self, principal: Principal, scope: Scope, department_id: UUID | None
    ) -> UUID | None:
        if scope is not Scope.ALL:
            # A head of sales always creates in their own department, whatever was sent.
            if principal.department_id is None:
                raise DomainValidationError("You are not assigned to a department.")
            return principal.department_id
        if department_id is not None:
            self._existing_department(principal, department_id)
        return department_id

    def _existing_department(self, principal: Principal, department_id: UUID) -> None:
        department = self._store.department(principal.tenant_id, department_id)
        if department is None or not department.is_active:
            raise DomainValidationError(
                "department_id is not an active department of this company."
            )

    def _managed(self, principal: Principal, scope: Scope, membership_id: UUID) -> StaffMember:
        member = self._store.member(principal.tenant_id, membership_id)
        if member is None:
            raise NotFoundError("Staff member not found.")
        if scope is not Scope.ALL:
            in_department = (
                member.department is not None and member.department.id == principal.department_id
            )
            manageable = {r.value for r in CREATABLE_ROLES.get(principal.role, ())}
            if not in_department or member.role not in manageable:
                raise NotFoundError("Staff member not found.")
        return member

    def _record(
        self, principal: Principal, action: str, kind: str, rid: str, fields: tuple[str, ...]
    ) -> None:
        self._audit.record(
            AuditEntry(
                actor_user_id=principal.user_id,
                action=action,
                resource_type=kind,
                resource_id=rid,
                changed_fields=fields,
            )
        )


def _clean(value: str, field: str, limit: int) -> str:
    cleaned = " ".join(value.split())
    if not cleaned:
        raise DomainValidationError(f"{field} must not be empty.")
    if len(cleaned) > limit:
        raise DomainValidationError(f"{field} must be at most {limit} characters.")
    return cleaned


def _login_from(first: str, last: str) -> str:
    base = ".".join(p for p in (first, last) if p).lower()
    ascii_only = re.sub(r"[^a-z0-9.]+", "", base)
    return ascii_only if len(ascii_only) >= 3 else "user"


def _unique_login(base: str, taken: Callable[[str], bool]) -> str:
    for n in range(2, 1000):
        candidate = f"{base}{n}"
        if not taken(candidate):
            return candidate
    raise ConflictError("Could not generate a free login; please choose one.")
